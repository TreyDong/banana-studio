let readSetting = () => 'auto';
let readHostLanguage = () => 'en';
function resolveLanguage(setting, hostLanguage = 'en') {
  const selected = setting === 'zh' || setting === 'en' ? setting : hostLanguage;
  return /^zh(?:[-_]|$)/i.test(String(selected)) ? 'zh' : 'en';
}
function configureLocale(settingReader, hostReader) {
  readSetting = settingReader;
  readHostLanguage = hostReader || (() => 'en');
}
function currentLanguage() {
  let host = 'en';
  try { host = readHostLanguage() || 'en'; } catch (_) { /* English fallback */ }
  return resolveLanguage(readSetting(), host);
}
